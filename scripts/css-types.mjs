/**
 * Generate the CSS Module type sidecar for `styles.module.css`.
 *
 * Why this file exists at all: the client bundle imports the stylesheet as a
 * CSS Module, and the only ambient declaration available for `*.module.css` is
 * a `Record<string, string>`. Under `noUncheckedIndexedAccess` an index
 * signature is read back as `string | undefined`, so every single
 * `styles.someClass` in the plugin would be a type error — and worse, a typo
 * would silently compile and render an unstyled element.
 *
 * A `.d.ts` sitting next to the stylesheet with one *explicit* key per class
 * fixes both problems at once: TypeScript prefers the sidecar over the ambient
 * wildcard, each class is a required property (so it reads back as `string`),
 * and a misspelled class becomes a compile error.
 *
 * The sidecar is generated rather than hand-written so it cannot drift; `verify`
 * re-runs this script in check mode and fails when the two disagree.
 *
 * Usage:
 *   node scripts/css-types.mjs           # write the sidecar
 *   node scripts/css-types.mjs --check   # exit 1 when the sidecar is stale
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cssPath = join(root, 'src', 'client', 'styles.module.css')
const dtsPath = join(root, 'src', 'client', 'styles.module.css.d.ts')
const check = process.argv.includes('--check')

/**
 * Class names declared at the top level of the stylesheet.
 *
 * Only a line that *starts* with a dot is a declaration; the same dot appears in
 * selectors like `.a .b`, in `:global(...)` and inside comments, so anchoring on
 * the line start is what keeps this from inventing names.
 */
function classNames(css) {
  const found = new Set()
  for (const line of css.split('\n')) {
    const match = /^\.([A-Za-z_][A-Za-z0-9_]*)/.exec(line)
    if (match) found.add(match[1])
  }
  return [...found].sort()
}

const css = await readFile(cssPath, 'utf8')
const names = classNames(css)
if (names.length === 0) {
  console.error('css-types: no class names found — has styles.module.css moved?')
  process.exit(1)
}

const body = [
  '/* Generated by scripts/css-types.mjs — do not edit by hand. */',
  'declare const classes: {',
  ...names.map((name) => `  readonly ${name}: string`),
  '}',
  'export default classes',
  '',
].join('\n')

if (check) {
  const current = await readFile(dtsPath, 'utf8').catch(() => '')
  if (current !== body) {
    console.error(
      `css-types: ${relative(root, dtsPath)} is stale — run \`node scripts/css-types.mjs\` and commit the result.`,
    )
    process.exit(1)
  }
  console.log(`css-types: ${names.length} classes, sidecar up to date`)
} else {
  await writeFile(dtsPath, body, 'utf8')
  console.log(`css-types: wrote ${names.length} classes to ${relative(root, dtsPath)}`)
}
